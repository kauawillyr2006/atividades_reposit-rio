create table if not exists public.ratings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id bigint not null references public.films(id) on delete cascade,
  rating integer not null check (rating between 1 and 10),
  comment varchar(280) not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, movie_id)
);

alter table public.films enable row level security;
alter table public.ratings enable row level security;

drop policy if exists "Anyone can read films" on public.films;
create policy "Anyone can read films"
on public.films for select
to anon, authenticated
using (true);

drop policy if exists "Signed-in users can read ratings" on public.ratings;
create policy "Signed-in users can read ratings"
on public.ratings for select
to authenticated
using (true);

drop policy if exists "Users can insert their own ratings" on public.ratings;
create policy "Users can insert their own ratings"
on public.ratings for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own ratings" on public.ratings;
create policy "Users can update their own ratings"
on public.ratings for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own ratings" on public.ratings;
create policy "Users can delete their own ratings"
on public.ratings for delete
to authenticated
using (auth.uid() = user_id);

